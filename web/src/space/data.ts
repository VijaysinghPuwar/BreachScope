// Reference data for the Space view. Every distance carries its source.
// Distances are measured from the origin of the view that shows them: Earth for the
// Earth and Moon view, the Sun for the Solar System and the Milky Way, and our galaxy
// beyond that. Directions (angleDeg) are schematic and only spread the labels out.

/** IAU 2012 Resolution B2: the astronomical unit is exactly 149,597,870,700 m. */
export const M_PER_AU = 149_597_870_700;
/** IAU: light speed (299,792,458 m/s, exact) times one Julian year (365.25 days). */
export const M_PER_LY = 9_460_730_472_580_800;
/** IAU 2015 Resolution B2: 1 pc = 648,000 / pi AU. */
export const M_PER_PC = (648_000 / Math.PI) * M_PER_AU;
/** Speed of light in m/s (SI, exact). */
export const LIGHT_SPEED = 299_792_458;

const KM = 1_000;
const KPC = 1_000 * M_PER_PC;
const MLY = 1e6 * M_PER_LY;
const GLY = 1e9 * M_PER_LY;

/**
 * orbit: ring centred on the origin plus a dot. body: a dot.
 * galaxy: a hollow dot. boundary: a ring with no dot.
 */
export type SpaceKind = 'orbit' | 'body' | 'galaxy' | 'boundary';

/**
 * proper: ordinary distance, fine for anything inside the Local Group.
 * light-travel: light travel time times c, the figure most press releases quote.
 * comoving: distance today, accounting for cosmic expansion.
 */
export type DistanceMeasure = 'proper' | 'light-travel' | 'comoving';

export interface SpaceObject {
  id: string;
  name: string;
  distanceM: number;
  angleDeg: number;
  kind: SpaceKind;
  measure: DistanceMeasure;
  note: string;
  source: string;
}

