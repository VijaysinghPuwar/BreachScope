// Reference data for the Space view. Every distance carries its source.
//
// Positions are real where the data allows: planets from JPL orbital elements for the
// shown date, the Moon from the Astronomical Almanac formula, stars and galaxies from
// their J2000 sky coordinates (SIMBAD, NED) at the quoted distance. Moons of other
// planets move at their real periods, but their starting phase is illustrative.
// Galaxy shapes, sizes and tilts are illustrative.

import type { KeplerElements } from './astro';
import type { GalaxyMorph, PlanetSkin } from './textures';

/** IAU 2012 Resolution B2: the astronomical unit is exactly 149,597,870,700 m. */
export const M_PER_AU = 149_597_870_700;
/** IAU: light speed (299,792,458 m/s, exact) times one Julian year (365.25 days). */
export const M_PER_LY = 9_460_730_472_580_800;
/** IAU 2015 Resolution B2: 1 pc = 648,000 / pi AU. */
export const M_PER_PC = (648_000 / Math.PI) * M_PER_AU;
/** Speed of light in m/s (SI, exact). */
export const LIGHT_SPEED = 299_792_458;

const KM = 1_000;
const KPC = 1_000 * M_PER_PC;
const MLY = 1e6 * M_PER_LY;
const GLY = 1e9 * M_PER_LY;

/**
 * proper: ordinary distance, fine for anything inside the Local Group.
 * light-travel: light travel time times c, the figure most press releases quote.
 * comoving: distance today, accounting for cosmic expansion.
 */
export type DistanceMeasure = 'proper' | 'light-travel' | 'comoving';

export type Placement =
  | { type: 'sun' }
  | { type: 'kepler'; elements: KeplerElements }
  | { type: 'earth' }
  | { type: 'moon' }
  | { type: 'l2' }
  /** Moon of another planet: real distance and period, illustrative phase. */
  | { type: 'satellite'; parent: string; periodDays: number; phaseDeg: number }
  /** A ring around Earth at distanceM, tilted to Earth's equator. */
  | { type: 'earth-orbit'; inclinationDeg: number }
  /** A sphere around the Sun at distanceM, drawn as its outline. */
  | { type: 'shell' }
  | { type: 'belt'; innerAu: number; outerAu: number; tiltDeg: number }
  /** J2000 right ascension (h m s) and declination (d m s). */
  | { type: 'sky'; ra: string; dec: string };

export type SpaceKind =
  | 'star'
  | 'planet'
  | 'dwarf-planet'
  | 'moon'
  | 'spacecraft'
  | 'orbit'
  | 'boundary'
  | 'belt'
  | 'nebula'
  | 'cluster'
  | 'galaxy'
  | 'galaxy-cluster'
  | 'quasar';

export interface SpaceObject {
  id: string;
  name: string;
  kind: SpaceKind;
  /** Distance quoted in the source, measured from `from`. */
  distanceM: number;
  from: 'Earth' | 'Sun' | 'Jupiter' | 'Saturn' | 'Mars' | 'Neptune';
  measure: DistanceMeasure;
  placement: Placement;
  note: string;
  source: string;
  radiusKm?: number;
  /** North pole J2000 RA and Dec in degrees (IAU WGCCRE 2015). */
  pole?: [number, number];
  skin?: PlanetSkin;
  rings?: boolean;
  color?: string;
  morph?: GalaxyMorph;
  /** Illustrative diameter for drawing galaxies and clusters. */
  sizeLy?: number;
}

